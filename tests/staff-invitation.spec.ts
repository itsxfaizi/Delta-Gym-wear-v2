import { randomUUID } from "node:crypto";
import { expect, test, type Page } from "@playwright/test";

import { assertSafeE2eTarget, E2E_EMAIL_DOMAIN, withDb } from "./db";
import { signInAsOwner } from "./helpers";

// Invite links and password setup are bearer credentials; never write them to traces.
test.use({ trace: "off" });

async function createInvitationLink(page: Page, email: string): Promise<string> {
  await signInAsOwner(page, "/admin/team");
  await page.getByLabel("Email address").fill(email);
  await page.getByRole("button", { name: "Create invitation link" }).click();
  const input = page.getByLabel("Staff invitation link");
  await expect(input).toBeVisible();
  const url = await input.inputValue();
  if (!url.startsWith("https://")) throw new Error("The invitation link was not created.");
  return url;
}

async function followInvitation(page: Page, url: string): Promise<void> {
  try { await page.goto(url); }
  catch { throw new Error("The invitation verification link could not be opened."); }
}

async function membershipForEmail(email: string) {
  const target = assertSafeE2eTarget();
  return withDb(async (sql) => {
    const [membership] = await sql`
      select m.auth_user_id, m.role, m.status
        from memberships m join auth.users u on u.id = m.auth_user_id
       where m.tenant_id = ${target.tenantId} and lower(u.email) = ${email.toLowerCase()}
    `;
    return membership;
  });
}

test("a staff member accepts the owner-created link, sets a password, and cannot replay it", async ({ page }) => {
  const email = `accept.${Date.now()}.${randomUUID()}@${E2E_EMAIL_DOMAIN}`;
  const inviteUrl = await createInvitationLink(page, email);
  const invited = await membershipForEmail(email);
  expect(invited).toMatchObject({ role: "auditor", status: "invited" });

  // Follow the actual Supabase action_link generated by the owner UI. The
  // default confirmation template returns its session in a URL fragment.
  await followInvitation(page, inviteUrl);
  await expect(page).toHaveURL(/\/reset-password\?next=%2Fadmin$/, { timeout: 60_000 });
  await expect(page.getByRole("heading", { name: "Choose a new password" })).toBeVisible();
  await expect((await membershipForEmail(email))?.status).toBe("invited");

  await page.getByLabel("New password", { exact: true }).fill("InvitedAuditor!2026");
  await page.getByLabel("Confirm new password", { exact: true }).fill("InvitedAuditor!2026");
  await page.getByRole("button", { name: "Update password" }).click();
  await expect(page).toHaveURL(/\/admin-mfa/, { timeout: 60_000 });
  await expect(page.getByRole("heading", { name: "Secure your staff account" })).toBeVisible();
  await expect((await membershipForEmail(email))?.status).toBe("active");

  // The accepted session is AAL1 and cannot reach an admin route before TOTP.
  await page.goto("/admin/products/new");
  await expect(page).toHaveURL(/\/admin-mfa/);

  // A consumed link cannot create another session after the first session ends.
  await page.context().clearCookies();
  await followInvitation(page, inviteUrl);
  await expect(page.getByRole("heading", { name: "Choose a new password" })).toHaveCount(0);
  await page.goto("/admin");
  await expect(page).toHaveURL(/\/login(?:\?|$)/);
});

test("cancelling a pending invitation records an audit event and blocks its link", async ({ page, browser }) => {
  const target = assertSafeE2eTarget();
  const email = `cancel.${Date.now()}.${randomUUID()}@${E2E_EMAIL_DOMAIN}`;
  const inviteUrl = await createInvitationLink(page, email);
  const invited = await membershipForEmail(email);
  expect(invited).toMatchObject({ role: "auditor", status: "invited" });

  const memberRow = page.locator("tr", { hasText: email });
  await expect(memberRow.getByRole("button", { name: "Cancel invitation" })).toBeEnabled();
  await memberRow.getByRole("button", { name: "Cancel invitation" }).click();
  await expect(memberRow).toContainText("Cancelled", { timeout: 30_000 });

  const cancellation = await withDb(async (sql) => {
    const [membership] = await sql`
      select status from memberships
       where tenant_id = ${target.tenantId} and auth_user_id = ${invited.auth_user_id}
    `;
    const [audit] = await sql`
      select action, outcome, before, after from audit_events
       where tenant_id = ${target.tenantId} and target_id = ${invited.auth_user_id}
         and action = 'team.invite_cancelled'
       order by created_at desc limit 1
    `;
    return { membership, audit };
  });
  expect(cancellation.membership?.status).toBe("cancelled");
  expect(cancellation.audit).toMatchObject({ action: "team.invite_cancelled", outcome: "success" });
  expect(cancellation.audit.before).toMatchObject({ status: "invited" });
  expect(cancellation.audit.after).toMatchObject({ status: "cancelled" });

  const invitee = await browser.newPage();
  try {
    await followInvitation(invitee, inviteUrl);
    await expect(invitee.getByRole("heading", { name: "Invitation unavailable" })).toBeVisible({ timeout: 60_000 });
    await expect(invitee.getByRole("heading", { name: "Choose a new password" })).toHaveCount(0);
    await invitee.goto("/admin");
    await expect(invitee).toHaveURL(/\/login(?:\?|$)/);
  } finally {
    await invitee.close();
  }

  await expect((await membershipForEmail(email))?.status).toBe("cancelled");
});
